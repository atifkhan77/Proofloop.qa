async function main() {
  const prisma = new PrismaClient();
  try {
    const orgs = await prisma.organization.findMany({ where: { name: ORG_NAME } });
    if (orgs.length !== 1) {
      throw new Error(`Expected exactly 1 organization named "${ORG_NAME}", found ${orgs.length}.`);
    }
    const org = orgs[0];

    let project = await prisma.project.findFirst({
      where: { organizationId: org.id, name: PROJECT_NAME },
    });
    if (!project) {
      project = await prisma.project.create({
        data: { name: PROJECT_NAME, description: PROJECT_DESCRIPTION, organizationId: org.id },
      });
      console.log(`Created project "${PROJECT_NAME}" (${project.id})`);
    }

    // Module 10 Defect model (2026-11-11): bugId, required reporter, no expected/actual columns.
    // Reporter = the organization's admin account; expected/actual are kept in the description.
    const reporter = await prisma.user.findFirst({
      where: { organizationId: org.id, email: REPORTER_EMAIL },
    });
    if (!reporter) throw new Error(`Reporter ${REPORTER_EMAIL} not found in "${ORG_NAME}".`);

    for (const [bugId, severity, status, title, stepsToReproduce, expectedResult, actualResult, fix] of ISSUES) {
      const data = {
        title,
        description: [
          `Expected: ${expectedResult}`,
          `Actual: ${actualResult}`,
          `Fix / resolution: ${fix}`,
          `Source: docs/ISSUE-LOG.md ${bugId}`,
        ].join('\n\n'),
        severity,
        status,
        stepsToReproduce,
      };
      await prisma.defect.upsert({
        where: { projectId_bugId: { projectId: project.id, bugId } },
        create: { ...data, bugId, projectId: project.id, reporterId: reporter.id },
        update: data,
      });
    }

    const byStatus = await prisma.defect.groupBy({
      by: ['status'],
      where: { projectId: project.id },
      _count: true,
    });
    console.log(`Upserted ${ISSUES.length} defects into "${ORG_NAME}" / "${PROJECT_NAME}".`);
    console.log(byStatus.map((s) => `${s.status}: ${s._count}`).join(', '));
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
